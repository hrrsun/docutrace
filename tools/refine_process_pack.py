def main():
    assert len(SPECS) == 49
    archive = ROOT / "history/process-review-initial"
    archive.mkdir(parents=True, exist_ok=True)
    rows = []
    for process, name, outputs, purpose, reference in SPECS:
        target = ROOT / "process-reviews" / f"{process}.md"
        if target.exists() and not (archive / target.name).exists():
            shutil.copyfile(target, archive / target.name)
        items = outputs.split(";")
        content = f"# {process} {name}\n\n版本 0.2，日期 2026-11-12，状态为待评审的项目适配稿。\n\n"
        content += f"## 本过程工作\n\n{purpose}。\n\n"
        content += f"## 当前输入与依据\n\n以[当前项目工作文件](../{reference})、启动文件 0.5、需求追踪和实际证据为输入。后续批准决定单独记录。\n\n"
        content += "## 输出及工作内容\n\n| 输出 ID | 输出候选 | 本项目处理与状态 |\n|---|---|---|\n"
        for i, item in enumerate(items, 1):
            oid = f"O-{process}-{i:02d}"
            if "更新" in item:
                handling = "按实际影响更新版本、追踪和日志；尚未发生的更新保留待执行"
            elif any(
                word in item
                for word in (
                    "协议",
                    "卖方",
                    "关闭记录",
                    "验收的",
                    "评价",
                    "移交",
                    "最终报告",
                    "核实的",
                    "绩效数据",
                    "测量结果",
                )
            ):
                handling = "执行后附实际参与人、时间、版本和证据；当前不代填完成或签字"
            else:
                handling = f"形成与本项目相关的内容，当前草案依据见 {reference}，待负责人评审"
            content += f"| {oid} | {item} | {handling} |\n"
            rows.append((oid, process, item, reference, "待评审或待实际执行"))
        content += "\n## 评审与执行记录\n\n| 条目 | 内容 |\n|---|---|\n| 负责人意见 | 待填写 |\n| 修订决定与依据 | 待处理 |\n| 证据和实际结果 | 以 evidence 目录已有记录为准，缺项待执行 |\n| 批准人及日期 | 未批准 |\n\n"
        content += "本文件逐项列出常见输出候选，仍需对照合法取得的教材正文核验完整性及适用性。输出清单不是已经完成的交付成果。\n"
        target.write_text(content, encoding="utf-8")
    with (ROOT / "output-register.csv").open("w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(["输出ID", "过程", "输出候选", "内容依据", "状态"])
        w.writerows(rows)
    print(f"49 distinct process drafts; {len(rows)} output candidates")


if __name__ == "__main__":
    main()
